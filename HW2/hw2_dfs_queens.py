def create_counts(board):
    n = len(board)

    columns = [0] * n
    diagonals = [0] * (2*n-1)
    otherDiagonals = [0] * (2*n-1)

    for eachR in range(n):
        eachC = board[eachR]
        columns[eachC] += 1
        diagonals[eachR-eachC+n-1] += 1
        otherDiagonals[eachR+eachC] += 1

    return columns, diagonals, otherDiagonals


def queen_conflicts(eachR, eachC, columns, diagonals, otherDiagonals):
    n = len(columns)
    return (columns[eachC]-1 + diagonals[eachR-eachC+n-1]-1 + otherDiagonals[eachR+eachC]-1)


def update_counts(eachR, eachC, amount, columns, diagonals, otherDiagonals):
    n = len(columns)

    columns[eachC] += amount
    diagonals[eachR-eachC+n-1] += amount
    otherDiagonals[eachR+eachC] += amount

