def is_place_in_next_row_valid_optimized(col, columns, size):
    row = len(columns)

    tempColumns = columns + [col]

    usedColumns = set()
    usedDiagonals = set()
    usedOtherDiagonals = set()

    # Check if the current queen conflicts with any existing queen
    for queen_row, queen_column in enumerate(tempColumns):
        if (queen_column in usedColumns or queen_row-queen_column in usedDiagonals or queen_row+queen_column in usedOtherDiagonals):
            return False

        usedColumns.add(queen_column)
        usedDiagonals.add(queen_row-queen_column)
        usedOtherDiagonals.add(queen_row+queen_column)

    # Check that each future row has at least one valid position
    for future_row in range(row+1, size):
        hasValidColumn = False

        for future_col in range(size):
            if (future_col not in usedColumns and future_row-future_col not in usedDiagonals and future_row+future_col not in usedOtherDiagonals):
                hasValidColumn = True
                break

        if not hasValidColumn:
            return False

    return True

