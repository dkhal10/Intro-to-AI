def solve_queens_simple_heuristic(n):
    iterations = 0
    moves = 0
    start = time.time()
    tempTime = time.time()

    # move = 0
    sidewaysMoves = 0
    maxSideways = 20

    board = []
    for i in range(n):
        board.append(random.randrange(n))

    columns, diagonals, otherDiagonals = create_counts(board)

    while True:
        if (time.time()-start)>.5:
            break

        conflicts = []
        for eachR in range(n):
            conflicts.append(queen_conflicts(
                eachR, board[eachR],
                columns, diagonals, otherDiagonals
            ))

        total = sum(conflicts)
        originalTotal = total

        if total == 0:
            break

        maxConflicts = max(conflicts)
        worstQueens = []

        for i in range(n):
            if conflicts[i] == maxConflicts:
                worstQueens.append(i)

        queen_most_conflicts = random.choice(worstQueens)

        iterations += 1
        possibleColumns = list(range(n))
        random.shuffle(possibleColumns)

        best = board[queen_most_conflicts]
        sidewaysOptions = []
        improved = False

        oldCol = board[queen_most_conflicts]
        oldConflicts = conflicts[queen_most_conflicts]

        # Temporarily remove queen from counts
        update_counts(queen_most_conflicts, oldCol, -1, columns, diagonals, otherDiagonals)
        for eachC in possibleColumns:
            if eachC == board[queen_most_conflicts]:
                continue

            newConflicts = (columns[eachC]+ diagonals[queen_most_conflicts-eachC+n-1] + otherDiagonals[queen_most_conflicts+eachC])
            newTotal = originalTotal - 2*oldConflicts + 2*newConflicts
            if newTotal < originalTotal:
                best = eachC
                improved = True
                break
            elif newTotal == originalTotal:
                sidewaysOptions.append(eachC)
        # print(board)
        if improved:
            board[queen_most_conflicts] = best
            moves += 1
            sidewaysMoves = 0
        elif len(sidewaysOptions) > 0 and sidewaysMoves < maxSideways:
            best = random.choice(sidewaysOptions)
            board[queen_most_conflicts] = best
            moves += 1
            sidewaysMoves += 1
        else:
            board = []
            for i in range(n):
                board.append(random.randrange(n))

            columns, diagonals, otherDiagonals = create_counts(board)

            tempTime = time.time()
            sidewaysMoves = 0
            continue
        update_counts(queen_most_conflicts, board[queen_most_conflicts], 1,columns, diagonals, otherDiagonals)
        if (time.time()-tempTime)>.2:
            board = []
            for i in range(n):
                board.append(random.randrange(n))

            columns, diagonals, otherDiagonals = create_counts(board)

            tempTime = time.time()
            sidewaysMoves = 0
